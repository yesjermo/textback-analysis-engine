#!/usr/bin/env python3
"""Rebuild the generated web files so the static web view works even when opened as a file.

  web/sample.js      <- examples/sample_chat.txt + examples/samples/ (the sample people)
  web/reply_data.js  <- tools/reply_data.json + reference/*.jsonl  (intents, templates, reference library)

Run after editing either source:  python3 tools/build_web.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    sample = (ROOT / "examples" / "sample_chat.txt").read_text(encoding="utf-8")
    data = json.loads((ROOT / "tools" / "reply_data.json").read_text(encoding="utf-8"))
    data["reference"] = {
        f.stem: [json.loads(line) for line in f.read_text(encoding="utf-8").splitlines() if line.strip()]
        for f in sorted((ROOT / "reference").glob("*.jsonl"))
    }
    header = "// Generated by tools/build_web.py. Do not edit by hand.\n"
    samples = json.loads((ROOT / "examples" / "samples" / "samples.json").read_text(encoding="utf-8"))
    for s in samples:
        s["text"] = (ROOT / s["file"]).read_text(encoding="utf-8")
        s["filename"] = Path(s["file"]).name  # its extension picks the parser in the browser
    (ROOT / "web" / "sample.js").write_text(
        header
        + "window.TEXTBACK_SAMPLE = "
        + json.dumps(sample, ensure_ascii=False)
        + ";\n"
        + "window.TEXTBACK_SAMPLES = "
        + json.dumps(samples, ensure_ascii=False, indent=2)
        + ";\n",
        encoding="utf-8",
    )
    (ROOT / "web" / "reply_data.js").write_text(
        header
        + "window.TEXTBACK_DATA = "
        + json.dumps(data, ensure_ascii=False, indent=2)
        + ";\n",
        encoding="utf-8",
    )
    print("wrote web/sample.js and web/reply_data.js")


if __name__ == "__main__":
    main()
